const CODE = { P: 'person', F: 'company', A: 'address', G: 'health', S: 'special_category' };

// Markierten Satz in Klartext + Soll-Spannen zerlegen.
export function parse(s) {
  const gold = [];
  let text = '';
  const re = /\{([PFAGS]):([^}]+)\}/g;
  let last = 0, m;
  while ((m = re.exec(s)) !== null) {
    text += s.slice(last, m.index);
    gold.push({ id: CODE[m[1]], start: text.length, end: text.length + m[2].length });
    text += m[2];
    last = m.index + m[0].length;
  }
  return { text: text + s.slice(last), gold };
}
